"""桌面壳桥接契约闸（TD-014 中「desktop 壳窗口交互无 UI 自动化」的代码侧替代）。

壳的真窗口交互（托盘、拖拽、更新弹窗）要靠 Tauri WebDriver + WebView2 才能自动化，
那是运行态、本轮按口径不做（见 docs/e2e-testing.md「未覆盖」）。但壳最容易坏的地方
其实**不需要开窗口**就能守住——Tauri v2 的命令要同时满足四件事才会真的能用：

1. Rust 里写了 ``#[tauri::command]``；
2. 在 ``main.rs`` 的 ``generate_handler!`` 里注册了（漏注册 → 前端 invoke 直接报
   "command not found"，且只有运行到那一步才暴露）；
3. `permissions/autogenerated/<cmd>.toml` 里有对应的 ``allow-<kebab>`` 权限；
4. ``capabilities/main.json`` 的 ``permissions`` 里放行了该权限（漏放行 → 运行时
   IPC 被 ACL 拒绝，前端只看到一句 "not allowed"，非常难查）。

再加上一条反向约束：``desktop-bridge.js`` 里写死的 invoke 名字必须都是已注册命令
（拼错一个字母就等于该功能永久静默失效）。这四条合起来就是「壳窗口交互」的
契约面，本文件把它变成每次 ``pytest`` 都会跑的静态闸。
"""

from __future__ import annotations

import json
import os
import re

PROJECT_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DESKTOP = os.path.join(PROJECT_ROOT, "desktop")
SRC_TAURI = os.path.join(DESKTOP, "src-tauri")
RUST_SRC = os.path.join(SRC_TAURI, "src")
PERMISSIONS = os.path.join(SRC_TAURI, "permissions", "autogenerated")
CAPABILITY = os.path.join(SRC_TAURI, "capabilities", "main.json")
BRIDGE_JS = os.path.join(DESKTOP, "src", "desktop-bridge.js")

_CMD_RE = re.compile(r"#\[tauri::command\][\s\S]{0,200}?fn\s+(\w+)\s*\(")
_REGISTER_BLOCK_RE = re.compile(r"generate_handler!\s*\[([\s\S]*?)\]")
_ALLOW_ID_RE = re.compile(r'identifier\s*=\s*"allow-([a-z0-9-]+)"')
_ALLOW_CMD_RE = re.compile(r"commands\.allow\s*=\s*\[(.*?)\]")
_BRIDGE_LITERAL_RE = re.compile(r'invoke\(\s*"([A-Za-z0-9_:|-]+)"')


def _read(path: str) -> str:
    with open(path, encoding="utf-8") as fh:
        return fh.read()


def _commands() -> dict[str, str]:
    """命令名 -> 所在 Rust 文件（相对 src-tauri/src）。"""
    found: dict[str, str] = {}
    for name in sorted(os.listdir(RUST_SRC)):
        if not name.endswith(".rs"):
            continue
        text = _read(os.path.join(RUST_SRC, name))
        for cmd in _CMD_RE.findall(text):
            found.setdefault(cmd, name)
    return found


def _registered() -> set[str]:
    """main.rs 里 generate_handler! 注册的命令名（取 :: 之后的最后一段）。"""
    text = _read(os.path.join(RUST_SRC, "main.rs"))
    block = _REGISTER_BLOCK_RE.search(text)
    assert block, "main.rs 里找不到 generate_handler![...] 注册块"
    names = set()
    for raw in block.group(1).split(","):
        entry = raw.strip()
        if not entry or entry.startswith("//"):
            continue
        names.add(entry.split("::")[-1].strip())
    return names


def _permissions() -> dict[str, set[str]]:
    """allow 权限 identifier -> 其 commands.allow 列表里的命令名。"""
    result: dict[str, set[str]] = {}
    for name in sorted(os.listdir(PERMISSIONS)):
        if not name.endswith(".toml"):
            continue
        text = _read(os.path.join(PERMISSIONS, name))
        ids = _ALLOW_ID_RE.findall(text)
        allow_block = _ALLOW_CMD_RE.search(text)
        commands = (
            set(re.findall(r'"([A-Za-z0-9_]+)"', allow_block.group(1))) if allow_block else set()
        )
        for ident in ids:
            result[f"allow-{ident}"] = commands
    return result


def _capability_permissions() -> list[str]:
    data = json.loads(_read(CAPABILITY))
    return list(data.get("permissions", []))


def _kebab_to_snake(kebab: str) -> str:
    return kebab.replace("-", "_")


def test_every_command_is_registered() -> None:
    commands = _commands()
    assert commands, "一个 #[tauri::command] 都没解析到——解析器或源码结构变了"
    registered = _registered()
    missing = sorted(set(commands) - registered)
    assert not missing, (
        "写了命令但没在 generate_handler! 注册（前端 invoke 会报 not found）: " f"{missing}"
    )
    orphan = sorted(registered - set(commands))
    assert not orphan, f"generate_handler! 注册了不存在的命令: {orphan}"


def test_every_command_has_autogenerated_allow_permission() -> None:
    commands = _commands()
    permissions = _permissions()
    missing: list[str] = []
    mismatched: list[str] = []
    for cmd in sorted(commands):
        ident = f"allow-{cmd.replace('_', '-')}"
        if ident not in permissions:
            missing.append(f"{cmd}（缺 {ident}）")
        elif cmd not in permissions[ident]:
            mismatched.append(f"{ident} 的 commands.allow 里没有 {cmd}")
    assert not missing, f"命令缺少 allow 权限文件: {missing}"
    assert not mismatched, f"权限与命令对不上: {mismatched}"


def test_every_command_is_allowed_by_capability() -> None:
    commands = _commands()
    allowed = _capability_permissions()
    assert allowed, "capabilities/main.json 的 permissions 为空"
    assert len(allowed) == len(set(allowed)), "capabilities/main.json 的 permissions 有重复项"

    missing = [cmd for cmd in sorted(commands) if f"allow-{cmd.replace('_', '-')}" not in allowed]
    assert not missing, f"命令存在但 capability 没放行（运行时 IPC 会被 ACL 拒绝）: {missing}"


def test_capability_entries_point_at_real_commands() -> None:
    commands = _commands()
    allowed = _capability_permissions()
    stray: list[str] = []
    for ident in allowed:
        if not ident.startswith("allow-"):
            continue  # core:default / notification:default / updater:default 等插件权限
        if _kebab_to_snake(ident[len("allow-") :]) not in commands:
            stray.append(ident)
    assert not stray, f"capability 放行了不存在的命令权限: {stray}"


def test_bridge_literals_are_registered_commands() -> None:
    text = _read(BRIDGE_JS)
    literals = {name for name in _BRIDGE_LITERAL_RE.findall(text) if not name.startswith("plugin:")}
    assert literals, "桥接脚本里没有解析到任何 invoke 字面量——解析器或写法变了"
    unknown = sorted(literals - set(_commands()) - _registered())
    assert not unknown, f"桥接 invoke 了不存在的命令（运行时会静默失效）: {unknown}"


def test_bridge_is_actually_injected_by_the_shell() -> None:
    """桥接脚本必须被 Rust 编译期内嵌并以 initialization_script 注入。

    否则「JS 写好了但壳没注入」这种断链在运行时表现为「桌面端按钮全无反应」，
    而浏览器里一切正常——正是 TD-014 说的「前端回归靠人肉」那一类问题。
    """
    window_rs = _read(os.path.join(RUST_SRC, "window.rs"))
    assert (
        "include_str!" in window_rs and "desktop-bridge.js" in window_rs
    ), "window.rs 未通过 include_str! 内嵌 desktop-bridge.js"
    assert "initialization_script" in window_rs, "window.rs 未调用 initialization_script 注入桥接"
